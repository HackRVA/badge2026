static unsigned int c_demo_wasm_len = 906;

static struct wasmrt wasm;

static enum wasmdemo_state_t {
	WASMDEMO_INIT = 0,
	WASMDEMO_RUN,
} wasmdemo_state = WASMDEMO_INIT;

static void wasmdemo_exit(void)
{
	wasmdemo_state = WASMDEMO_INIT;
	wasmrt_cleanup(&wasm);
	pop_app();
}

static void check_buttons(void)
{
	int down_latches = button_down_latches();
	if (BUTTON_PRESSED(BADGE_BUTTON_B, down_latches)) {
		wasmdemo_exit();
	}
}

void cwasmdemo_cb(__attribute__((unused)) struct menu_t *m)
{
	switch (wasmdemo_state) {
	case WASMDEMO_INIT:
		wasmdemo_state = WASMDEMO_RUN;
		wasm = wasmrt_create();
		wasmrt_load_app(&wasm, c_demo_wasm, c_demo_wasm_len);
		break;
	case WASMDEMO_RUN:
		wasmrt_update(&wasm);
		break;
	default:
		break;
	}
	check_buttons();
}
